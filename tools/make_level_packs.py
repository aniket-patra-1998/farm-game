#!/usr/bin/env python3
"""Puts every item's model files that a new player does not need yet into a pack for its unlock level
(docs/PACKS.md "Online", step 3): data/level_packs.json, read by AssetPacks; and leaves those files out of the
Play Store build (export_presets.cfg, the AAB preset's exclude_filter). Items of the first levels
(data/packs.json `starter_level`), crops, blooms and the farmer stay in the app; an item never in the Market
(a stray, a lost animal, a plain baby: unlock level 99) goes in the pack "extras", fetched at the start.
The debug and benchmark APKs keep every file, so the phone bench draws the same farm. --check: fail when
either file is not what this would write."""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "data", "level_packs.json")
PRESETS = os.path.join(ROOT, "export_presets.cfg")
AAB = "Android (Play Store AAB)"
NEVER = 99
SPLIT = 12 * 1048576   # most source bytes in one extras pack (the made files are bigger; Pages takes 25 MiB)
KEEP_PREFIX = ("crop:",)
KEEP_DIRS = ("art/models/limited/", "art/models/crops/", "art/models/blooms/", "art/models/farmer/")


def levels():
    """item id -> (unlock level, baby id or "")."""
    schema = json.load(open(os.path.join(ROOT, "data", "catalog", "schema.json")))
    out = {}
    for cat in schema["files"]:
        d = json.load(open(os.path.join(ROOT, "data", "catalog", cat + ".json")))
        for fam in d["families"]:
            for v in fam["variants"]:
                e = {"unlock_level": 1}
                e.update(d.get("defaults", {})); e.update(fam.get("defaults", {})); e.update(v)
                if e.get("status") == "planned":
                    continue
                out[v["id"]] = (int(e["unlock_level"]), str(e.get("baby", "")))
    return out


def files_of(entry):
    found = []
    for key in ("model", "site", "broken"):
        path = entry.get(key, "")
        if not path:
            continue
        pattern = re.sub(r"\{[a-z]+\}", "*", path.replace("res://", ""))
        found += ["res://" + os.path.relpath(f, ROOT) for f in sorted(glob.glob(os.path.join(ROOT, pattern)))]
    return found


def build():
    starter = int(json.load(open(os.path.join(ROOT, "data", "packs.json"))).get("starter_level", 5))
    item = levels()
    babies = {}
    for iid, (lvl, baby) in item.items():
        if baby and lvl < NEVER:
            babies[baby] = min(babies.get(baby, NEVER), lvl)
    assets = json.load(open(os.path.join(ROOT, "data", "assets.json")))["assets"]
    packs = {}
    for iid, entry in assets.items():
        files = files_of(entry)
        if iid.startswith(KEEP_PREFIX) or not files or any(f.startswith("res://" + d) for f in files for d in KEEP_DIRS):
            continue
        lvl = item.get(iid, (NEVER, ""))[0]
        if lvl >= NEVER and entry.get("budget") == "building":
            continue   # (never sold: the starter Barn, there from the first minute)
        if lvl >= NEVER:
            lvl = babies.get(iid, NEVER)
        if lvl <= starter:
            continue
        name = "extras" if lvl >= NEVER else "level_%02d" % lvl
        pack = packs.setdefault(name, {"level": 0 if lvl >= NEVER else lvl, "files": []})
        pack["files"] += files
    for p in packs.values():
        p["files"] = sorted(set(p["files"]))
    if "extras" in packs:   # (split, so each pack stays well under Cloudflare Pages' 25 MiB a file)
        files = packs.pop("extras")["files"]
        part, size, n = [], 0, 1
        for f in files + [None]:
            grow = 0 if f is None else os.path.getsize(os.path.join(ROOT, f.replace("res://", "")))
            if f is None or (part and size + grow > SPLIT):
                packs["extras_%d" % n] = {"level": 0, "files": part}
                part, size, n = [], 0, n + 1
            if f is not None:
                part.append(f); size += grow
    packs = dict(sorted(packs.items()))
    doc = ("Generated by tools/make_level_packs.py; do not edit. Each item's model files a new player does not need "
           "yet, packed by unlock level (docs/PACKS.md, Online). AssetPacks fetches a level's pack once the player is "
           "a level below it, and extras at the start; the Play Store build leaves these files out.")
    return {"_doc": doc, "starter_level": starter, "packs": packs}


def presets_with(data):
    text = open(PRESETS).read()
    files = [f.replace("res://", "") for p in data["packs"].values() for f in p["files"]]
    parts = re.split(r"(?m)^(?=\[preset\.\d+\]$)", text)
    out = []
    for part in parts:
        if 'name="%s"' % AAB in part:
            def repl(m):
                kept = [x.strip() for x in m.group(1).split(",") if x.strip() and not x.strip().startswith("art/models/") or x.strip() == "art/models/limited/*"]
                return 'exclude_filter="%s"' % ", ".join(kept + files)
            part = re.sub(r'(?m)^exclude_filter="([^"]*)"', repl, part, count=1)
        out.append(part)
    return "".join(out)


def main():
    data = build()
    text = json.dumps(data, indent=1) + "\n"
    presets = presets_with(data)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text and open(PRESETS).read() == presets
        n = sum(len(p["files"]) for p in data["packs"].values())
        print("the level packs are up to date (%d packs, %d files)" % (len(data["packs"]), n) if ok
              else "data/level_packs.json or export_presets.cfg is stale: run python3 tools/make_level_packs.py")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    open(PRESETS, "w").write(presets)
    for name, p in data["packs"].items():
        size = sum(os.path.getsize(os.path.join(ROOT, f.replace("res://", ""))) for f in p["files"])
        print("%-10s %3d files %6.1f MB" % (name, len(p["files"]), size / 1048576))


main()
